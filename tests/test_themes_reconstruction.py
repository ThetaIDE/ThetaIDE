def parity_input(tmp_path):
    with np.load(FIXTURES / 'themes_parity.npz', allow_pickle=False) as fixture:
        saved = {k: fixture[k] for k in fixture.files}
    path = tmp_path / 'synthetic.npz'
    np.savez_compressed(path, **{k: saved[k] for k in ('X', 'mask', 'y', 'vids', 'feature_names_x', 'synthetic')})
    return path, saved


def test_extraction_matches_original_reconstruction(tmp_path):
    path, expected = parity_input(tmp_path)
    data = load_data(path, 0, 42)
    prepared = prepare(data, 42)
    for key in ('mean', 'scale', 'lower', 'span', 'policy_states'):
        np.testing.assert_allclose(prepared[key], expected[key], rtol=1e-5, atol=1e-6)
    np.testing.assert_array_equal(prepared['splits'], expected['splits'])
    original_threads = torch.get_num_threads()
    torch.set_num_threads(2)
    try:
        ticc = MultiSeriesTICC(2, 0.01, 4, 2, 42).fit([
            x for x, s in zip(prepared['state_episodes'], prepared['splits']) if s == 'train'])
        stages = ticc.predict(prepared['state_episodes'])
        labels = np.concatenate(stages)
        # Cluster numbers are arbitrary; compare the partitions, then parameters
        # under their induced label mapping.
        np.testing.assert_array_equal(labels[:, None] == labels, expected['labels'][:, None] == expected['labels'])
        for label in np.unique(labels):
            ref = expected['labels'][labels == label][0]
            np.testing.assert_allclose(ticc.means[label], expected['stage_means'][ref], rtol=1e-5, atol=1e-6)
            np.testing.assert_allclose(ticc.precisions[label], expected['stage_precisions'][ref], rtol=1e-5, atol=1e-6)
        segments = make_segments(stages, prepared['offsets'], prepared['splits'])
        np.testing.assert_array_equal([s.start for s in segments], expected['segment_starts'])
        np.testing.assert_array_equal([s.stop for s in segments], expected['segment_stops'])
        actions = np.concatenate(data['actions'])
        mixture = EMEDM(2, 2, 3, 1, 0.1, 42, 1, policy_factory=__import__("themes_al.models", fromlist=["historical_policy"]).historical_policy).fit(prepared['policy_states'], actions, prepared['valid'], segments)
        probabilities, evidence = mixture.predict(prepared['policy_states'], actions, prepared['valid'], segments)
        np.testing.assert_allclose(evidence, expected['evidence'], rtol=1e-5, atol=1e-6)
        np.testing.assert_allclose(np.sort(probabilities, axis=1), np.sort(expected['probabilities'], axis=1), rtol=1e-5, atol=1e-6)
    finally:
        torch.set_num_threads(original_threads)


