def test_heldout_values_do_not_change_fitted_scalers(tmp_path):
    path, _ = parity_input(tmp_path)
    data = load_data(path, 0, 42)
    before = prepare(data, 42)
    for i, split in enumerate(before['splits']):
        if split == 'test':
            data['observations'][i] += 1e6
    after = prepare(data, 42)
    for key in ('mean', 'scale', 'lower', 'span'):
        np.testing.assert_array_equal(before[key], after[key])
    train = before['row_train']
    np.testing.assert_array_equal(before['policy_states'][train], after['policy_states'][train])


def test_marginal_evidence_includes_priors_and_all_components():
    scores = np.log([[0.9, 0.2], [0.3, 0.8]])
    priors = np.array([0.25, 0.75])
    _, evidence = responsibilities(scores, priors)
    np.testing.assert_allclose(np.exp(evidence), np.exp(scores) @ priors)
    assert not np.allclose(evidence, scores.max(axis=1))


