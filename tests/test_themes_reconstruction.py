class AlgorithmsTest(unittest.TestCase):
    def test_viterbi_matches_exhaustive_minimum(self):
        rng = np.random.default_rng(9)
        for length in range(1, 6):
            cost = rng.normal(size=(length, 3))
            beta = 0.8
            labels = viterbi(cost, beta)
            objective = lambda path: sum(cost[t, k] for t, k in enumerate(path)) + beta * sum(
                a != b for a, b in zip(path[:-1], path[1:]))
            optimum = min(map(objective, itertools.product(range(3), repeat=length)))
            self.assertAlmostEqual(objective(labels), optimum)

    def test_precision_is_positive_definite_and_block_toeplitz(self):
        rng = np.random.default_rng(7)
        a = rng.normal(size=(6, 6))
        precision, diagnostic = sparse_toeplitz_precision(a.T @ a + np.eye(6), 3, 0.02)
        np.testing.assert_allclose(precision[:3, :3], precision[3:, 3:], atol=1e-12)
        np.testing.assert_allclose(precision, precision.T, atol=1e-12)
        self.assertGreater(np.linalg.eigvalsh(precision).min(), 0)
        self.assertTrue(diagnostic['converged'])

    def test_windows_do_not_join_patients(self):
        episodes = [np.array([[1.], [2.]]), np.array([[99.]])]
        windows, offsets = stack_windows(episodes)
        np.testing.assert_array_equal(windows, [[1, 1], [1, 2], [99, 99]])
        np.testing.assert_array_equal(offsets, [0, 2, 3])

    def test_segments_cover_exactly_once_and_preserve_boundaries(self):
        labels = [np.array([0, 0, 1, 0]), np.array([0])]
        segments = make_segments(labels, np.array([0, 4, 5]), ['train', 'test'])
        self.assertEqual([(s.patient, s.start, s.stop) for s in segments],
                         [(0, 0, 2), (0, 2, 3), (0, 3, 4), (1, 4, 5)])

    def test_long_segment_posteriors_do_not_underflow(self):
        probs, evidence = responsibilities(np.array([[-50000., -51000.], [0., 0.]]), [0.4, 0.6])
        self.assertTrue(np.isfinite(probs).all() and np.isfinite(evidence).all())
        np.testing.assert_allclose(probs.sum(axis=1), 1)
        np.testing.assert_allclose(probs[1], [0.4, 0.6])


class DataTest(unittest.TestCase):
    def test_padding_action_exclusion_lag_and_training_only_scalers(self):
        names = [f'{f}_mean' for f in PHYSIOLOGY] + [
            'ControlOxygen_max', ACTION, 'VasopressorAdmin_max']
        x = np.full((20, 5, len(names)), 99999.0)
        mask = np.full((20, 5, 1), -1.)
        for i in range(20):
            x[i, 2:, :14] = np.arange(3)[:, None] + i * 10
            x[i, 2:, 14:] = 0
            x[i, 3, names.index(ACTION)] = 1
            mask[i, 2:] = 0
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / 'fixture.npz'
            np.savez(path, X=x, mask=mask, y=np.arange(20) % 2,
                     vids=np.array([f'visit{i}' for i in range(20)]),
                     feature_names_x=np.array(names, dtype=object))
            data = load_data(path, 0, 42)
        prepared = prepare(data, 42)
        self.assertEqual(prepared['raw'].shape, (60, 14))
        self.assertEqual(prepared['policy_states'].shape, (60, 42))
        np.testing.assert_array_equal(data['slots'][0], [2, 3, 4])
        self.assertFalse(prepared['valid'][::3].any())
        for start in prepared['offsets'][:-1]:
            # Row 0 unscored; row 1 uses row 0 measurements, never row 1 action.
            np.testing.assert_array_equal(prepared['policy_states'][start],
                                          prepared['policy_states'][start + 1])
        raw = prepared['raw']
        train = prepared['row_train']
        np.testing.assert_allclose(prepared['mean'], raw[train].mean(axis=0))
        self.assertLess(raw.max(), 99999)


