"""Regenerate docs/reference/THIRD_PARTY_LIBRARIES.md from declared dependencies.

Reads the requirements in ``pyproject.toml`` (core and extras) and the pip
dependencies declared by the optional components in ``optional_components/``,
then looks up each package's installed version and licence in the current
environment. Run it with the project's environment:

    venv/bin/python scripts/generate_third_party_libraries.py

Packages that are not installed locally are listed without a version or
licence. Use ``--check`` to fail when the document is out of date.
"""
from __future__ import annotations

import argparse
import importlib.metadata as metadata
import json
import sys
import tomllib
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/reference/THIRD_PARTY_LIBRARIES.md"
COPYLEFT = ("GPL", "LGPL", "AGPL", "MPL")
# Hand-written context for copyleft rows; the licence itself always comes from metadata.
COPYLEFT_NOTES = {
    "pyqt6": "The GUI is built on it. Riverbank dual-licenses PyQt6: GPL-3.0, or a paid commercial licence. "
             "Distributing a binary that links it under GPL terms means the combined work is offered under the GPL.",
    "pyqt6-webengine": "Same terms; used by the embedded terminal and documentation views.",
    "tqdm": "Weak copyleft, file-level. Unmodified use imposes no obligation on the rest of the project.",
    "pygame": "Optional `video` extra. LGPL allows use from non-GPL code; redistributing pygame itself carries LGPL obligations.",
    "vidmaker": "Optional `video` extra. GPL-3.0: a distributed build that bundles it is subject to the GPL, as with PyQt6.",
}

HEADER = """# Third-Party Libraries

Every dependency ThetaIDE declares, with the licence of the version actually
installed. Generated by `scripts/generate_third_party_libraries.py` from
`pyproject.toml`, the optional components' declared pip dependencies and the
installed package metadata; do not edit it by hand. Regenerate after changing
dependencies.
"""

FOOTER = """
This is a statement of the facts, not legal advice. The practical reading is
that running and developing ThetaIDE is unencumbered, while *distributing* a
packaged build needs either GPL-compatible terms or a commercial Qt licence.
Worth settling before any public release.
"""


def licence(dist) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.rsplit(" :: ", 1)[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    declared = (meta.get("License") or "").strip()
    if declared and "\n" not in declared and len(declared) <= 60 and declared.upper() != "UNKNOWN":
        return declared
    if classifiers:
        return " / ".join(dict.fromkeys(classifiers))
    return "see project" if declared else "UNKNOWN"


def homepage(dist) -> str | None:
    meta = dist.metadata
    urls = {}
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        urls[label.strip().lower()] = url.strip()
    for key in ("homepage", "home", "documentation", "source", "repository"):
        if urls.get(key):
            return urls[key]
    return meta.get("Home-page") or next(iter(urls.values()), None)


def row(spec: str, note: str = "") -> tuple[str, str, str, str, str]:
    requirement = Requirement(spec)
    try:
        dist = metadata.distribution(requirement.name)
    except metadata.PackageNotFoundError:
        return requirement.name, requirement.name, "—", "not installed locally", f"`{spec}`{note}"
    url = homepage(dist)
    name = dist.metadata["Name"]
    label = f"[{name}]({url})" if url else name
    return name, label, dist.version, licence(dist), f"`{spec}`{note}"


def sections() -> list[tuple[str, list[tuple[str, str, str, str, str]]]]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    own = project["name"].lower()
    result = [("Core (always installed)", [row(s) for s in project["dependencies"]])]
    for extra, specs in project.get("optional-dependencies", {}).items():
        rows = [row(s) for s in specs if Requirement(s).name.lower() != own]
        if rows:
            result.append((f"`{extra}` extra", rows))
    for manifest in sorted((ROOT / "optional_components").glob("*/.theta_component.json")):
        data = json.loads(manifest.read_text(encoding="utf-8"))
        specs = (data.get("dependencies") or {}).get("pip") or []
        if specs:
            component = data.get("id") or manifest.parent.name
            result.append((f"`{component}` optional component (installed with the component, not with ThetaIDE)",
                           [row(s) for s in specs]))
    return result


def render() -> str:
    parts = [HEADER]
    groups = sections()
    copyleft = {}
    for _, rows in groups:
        for name, label, _, lic, _ in rows:
            if any(tag in lic.upper() for tag in COPYLEFT):
                copyleft.setdefault(name.lower(), (name, lic))
    parts.append("## Licences that constrain how ThetaIDE may be distributed\n")
    parts.append("ThetaIDE itself is MIT (see [LICENSE.md](../../LICENSE.md)). These declared dependencies are copyleft:\n")
    parts.append("| Package | Licence | Why it matters |\n|---|---|---|")
    for key, (name, lic) in sorted(copyleft.items()):
        parts.append(f"| {name} | {lic} | {COPYLEFT_NOTES.get(key, '')} |")
    parts.append(FOOTER)
    parts.append("## Full dependency table\n")
    parts.append("`Version in use` is what is installed in the environment that generated this file; "
                 "`Declared as` is the declared requirement.\n")
    for title, rows in groups:
        parts.append(f"### {title}\n")
        parts.append("| Package | Version in use | Licence | Declared as |\n|---|---|---|---|")
        for _, label, version, lic, declared in sorted(rows, key=lambda r: r[0].lower()):
            parts.append(f"| {label} | {version} | {lic} | {declared} |")
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the document is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
